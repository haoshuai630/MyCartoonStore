package org.csu.mycartoonstore.payment.domain; // 支付结果：区分"本次成功""之前已付""本次失败"三种结局。

// M06-01：依据 docs/01 FR-P-01 第 3～5 条。
// 只描述一次支付动作的结果，不携带金额与凭证：页面要展示的值一律从订单表读真实数据。
// 不定义"支付中"这类状态：模拟支付是同步完成的，没有异步回调。
public enum PaymentResult {

    PAID, // 本次真的把订单从待支付迁到了已支付。

    ALREADY_PAID, // 之前已经付过：凭证与支付时间保持首次的值，本次不再写库。

    FAILED // 模拟失败：只回支付页提示可重试，数据库没有任何变化。
}
